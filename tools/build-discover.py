#!/usr/bin/env python3
"""Build the /discover/ gallery from the app's own Discover catalogue.

    python3 tools/build-discover.py <app>

<app> is a CartoVox checkout (or a source export of the released tag). The
script reads web/assets/discover/catalogue.json, re-encodes the pictures of the
curated entries below as 560 px WebP files in img/discover/, and rewrites the
gallery between the markers in discover/index.html. Names, pitches, kinds and
rarities come from the catalogue verbatim, so the page cannot drift from what
the app's Discover offers. Run tools/stamp-assets.py afterwards.
"""
from __future__ import annotations

import html
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "img" / "discover"
PAGE = ROOT / "discover" / "index.html"
START = "<!-- discover gallery: generated by tools/build-discover.py -->"
END = "<!-- /discover gallery -->"

# A small, varied shelf: the strangest planets first, then each other kind.
CURATED = [
    "ringed-world", "tidally-locked", "tepui-karst", "two-suns", "volcanic-arc",
    "desert-planet", "shattered-archipelago", "great-rivers", "high-magic",
    "snowball", "fjord-coast", "exomoon",
    "the-gilded-rim", "the-lantern-crown", "wheel-of-rain",
    "the-lantern-sea", "the-twin-lamps",
    "the-fjordmark", "the-cinnamon-isles", "ashen-teeth",
    "aurenmark", "corvanta", "tamsa-wells",
    "castle-greyhallow", "the-drowned-temple", "the-bone-galleries",
    "the-sovereigns-mercy", "the-cloud-lark",
    "the-drowned-lantern", "the-last-gate", "the-velvet-court",
    "style-portolan", "style-woodcut", "style-night-atlas", "style-victorian-survey",
]

KIND = {  # catalogue kind -> (filter group, label)
    None: ("worlds", "World"), "region": ("worlds", "Region"),
    "disc": ("worlds", "Disc world"), "flat": ("worlds", "Flat world"),
    "city": ("cities", "City"), "dungeon": ("scenes", "Dungeon"),
    "ship": ("scenes", "Ship"), "scene": ("scenes", "Scene"),
    "tabletop": ("scenes", "Tabletop"), "style": ("styles", "Style pack"),
}
# Pictures that are plans or keys sit whole on a dark ground; maps fill.
CONTAIN = {"city", "dungeon", "ship", "scene", "tabletop", "disc"}


def picture(app: Path, row: dict) -> Path:
    base = app / "web" / "assets" / "discover" / row["id"]
    if (base / "plate.webp").exists() and row.get("kind") not in {"disc"}:
        return base / "plate.webp"
    if (base / "map.webp").exists():
        return base / "map.webp"
    return app / "web" / row["picture"]


def encode(src: Path, dest: Path, width: int = 560) -> tuple[int, int]:
    im = Image.open(src)
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest, "WEBP", quality=76, method=6)
    return im.size


def card(row: dict, size: tuple[int, int], number: int) -> str:
    group, label = KIND[row.get("kind")]
    rarity = row.get("rarity")
    tag = f"{rarity.capitalize()} world" if rarity else label
    fit = " is-contain" if row.get("kind") in CONTAIN else ""
    name = html.escape(row["name"])
    pitch = html.escape(row.get("pitch", ""))
    alt = html.escape(f"{label} {row['name']} from Discover: {row.get('pitch', '')}".strip())
    return (
        f'      <li class="disc-card" data-group="{group}">\n'
        f'        <figure>\n'
        f'          <div class="disc-media{fit}"><img src="/img/discover/{row["id"]}.webp" '
        f'width="{size[0]}" height="{size[1]}" alt="{alt}" loading="lazy" decoding="async"></div>\n'
        f'          <figcaption><span class="disc-label"><span class="disc-kind">{html.escape(tag)}</span>'
        f'<span class="disc-no">No.&nbsp;{number:02d}</span></span>'
        f'<b>{name}</b><span>{pitch}</span></figcaption>\n'
        f'        </figure>\n'
        f'      </li>'
    )


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    app = Path(sys.argv[1]).expanduser().resolve()
    catalogue = json.loads((app / "web/assets/discover/catalogue.json").read_text("utf-8"))
    rows = {r["id"]: r for r in [*catalogue["worlds"], *catalogue["entries"]]}
    cards = []
    for number, entry_id in enumerate(CURATED, 1):
        row = rows[entry_id]
        size = encode(picture(app, row), OUT / f"{entry_id}.webp")
        cards.append(card(row, size, number))
    counts = {}
    for row in rows.values():
        counts[KIND[row.get("kind")][0]] = counts.get(KIND[row.get("kind")][0], 0) + 1
    block = f"{START}\n" + "\n".join(cards) + f"\n      {END}"
    text = PAGE.read_text("utf-8")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    PAGE.write_text(head + block + tail, "utf-8")
    total = sum(f.stat().st_size for f in OUT.glob("*.webp"))
    print(f"{len(cards)} cards, {total / 1024:.0f} KB of pictures; catalogue holds "
          f"{len(rows)} items: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
